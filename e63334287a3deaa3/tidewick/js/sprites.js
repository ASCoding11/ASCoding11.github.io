function render(rows, sub, hoodAs = '2') {
  const h = rows.length, w = rows[0].length;
  const cv = makeCanvas(w, h), cx = cv.getContext('2d');
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    let ch = rows[y][x];
    if (ch === 'h') ch = hoodAs;
    if (ch === '1' || ch === '2' || ch === '3') { cx.fillStyle = PALETTE[sub[+ch - 1]]; cx.fillRect(x, y, 1, 1); }
  }
  return cv;
}
let makeCanvas = (w, h) => { const c = document.createElement('canvas'); c.width = w; c.height = h; return c; };
export function setCanvasMaker(fn) { makeCanvas = fn; }

// how many colours a grid uses (for the sheet test)
export function coloursIn(rows) { const s = new Set(); for (const r of rows) for (const c of r) if (c !== '.') s.add(c === 'h' ? '2' : c); return s.size; }

export const GRIDS = {};
export function buildSprites() {
  const S = {};
  const add = (name, rows, w, h, sub, hoodAs) => { const g = norm(rows, w, h); GRIDS[name] = g; S[name] = render(g, sub, hoodAs); return S[name]; };
  const pipSets = [['', PAL.pip], ['F', PAL.pipFire]].concat(PAL.star.map((s, i) => ['S' + i, s]));
  for (const [suf, pal] of pipSets) {
    for (const k in PIP_S) add('pipS_' + k + suf, PIP_S[k], 16, 16, pal);
    for (const k in PIP_B) add('pipB_' + k + suf, PIP_B[k], 16, 32, pal, suf === 'F' ? '3' : '2');
  }
  for (const k in BILGE) add('bilge_' + k, BILGE[k], 16, 16, PAL.bilge);
  add('whelk_walk1', WHELK.walk1, 16, 16, PAL.whelk); add('whelk_walk2', WHELK.walk2, 16, 16, PAL.whelk);
  add('whelkW_walk1', WHELK.walk1, 16, 16, PAL.whelkWary); add('whelkW_walk2', WHELK.walk2, 16, 16, PAL.whelkWary);
  add('whelk_shell', WHELK.shell, 16, 16, PAL.whelkShell); add('whelkW_shell', WHELK.shell, 16, 16, PAL.waryShell);
  for (const k of ['button0', 'button1', 'button2']) add(k, ITEMS[k], 16, 16, PAL.button);
  add('loaf', ITEMS.loaf, 16, 16, PAL.loaf);
  add('pepper0', ITEMS.pepper0, 16, 16, PAL.pepper); add('pepper1', ITEMS.pepper1, 16, 16, PAL.pepper);
  add('jar0', ITEMS.jar0, 16, 16, PAL.jar); add('jar1', ITEMS.jar1, 16, 16, PAL.jar);
  add('clover', ITEMS.clover, 16, 16, PAL.clover);
  add('spark0', SMALL.spark0, 8, 8, PAL.spark); add('spark1', SMALL.spark1, 8, 8, PAL.spark);
  add('bolt0', SMALL.bolt0, 24, 8, PAL.bolt); add('bolt1', SMALL.bolt1, 24, 8, PAL.bolt);
  add('plank', SMALL.plank, 8, 8, PAL.plank); add('smoke', SMALL.smoke, 8, 8, PAL.smoke);
  add('gull0', SMALL.gull0, 8, 8, PAL.gull); add('gull1', SMALL.gull1, 8, 8, PAL.gull);
  // the boss: a mirrored body, claws and legs per pose
  const half = norm(BOSS_HALF.body, 16, 32);
  const body = half.map(r => r + r.split('').reverse().join(''));
  const legs = (rows, lift) => rows.map((r, y) => {
    if (y < 20) return r;
    const src = body[Math.min(31, y + (y >= 20 ? lift : 0))] || '.'.repeat(32);
    return src;
  });
  const claw = norm(BOSS_CLAW, 12, 12), clawM = mirror(claw);
  const withClaws = (rows, dy) => rows.map((r, y) => {
    const a = r.split('');
    const cy = y - (8 + dy);
    if (cy >= 0 && cy < 12) for (let x = 0; x < 12; x++) {
      if (claw[cy][x] !== '.') a[x] = claw[cy][x];
      if (clawM[cy][x] !== '.') a[20 + x] = clawM[cy][x];
    }
    return a.join('');
  });
  const paceA = withClaws(body, 0);
  const paceB = withClaws(body.map((r, y) => y >= 20 ? (body[y - 1] || r) : r), 1);
  const hop = withClaws(body, -4);
  const spit = withClaws(body.map((r, y) => y === 18 ? r.replace(/3{4,}/, m => '1'.repeat(m.length)) : y === 19 ? r.replace(/3/g, '1') : r), 0);
  const fall = paceA.slice().reverse();
  for (const [n, rows] of [['pace1', paceA], ['pace2', paceB], ['hop', hop], ['spit', spit], ['fall', fall]]) {
    add('boss_' + n, rows, 32, 32, PAL.boss);
    add('bossHit_' + n, rows, 32, 32, PAL.bossHit);
  }
  void legs;
  // tiles
  add('t_cobble', TILES.cobble, 16, 16, PAL.cobble);
  add('t_fort', TILES.stone, 16, 16, PAL.fort);
  add('t_cellar', TILES.stone, 16, 16, PAL.cellar);
  add('t_stair', TILES.stair, 16, 16, PAL.stair);
  add('t_planks', TILES.planks, 16, 16, PAL.planks);
  PAL.lantern.forEach((pl, i) => add('t_lantern' + i, TILES.lantern, 16, 16, pl));
  add('t_used', TILES.used, 16, 16, PAL.used);
  add('t_lipL', TILES.lipL, 16, 16, PAL.chimney); add('t_lipR', mirror(norm(TILES.lipL, 16, 16)), 16, 16, PAL.chimney);
  add('t_shaftL', TILES.shaftL, 16, 16, PAL.chimney); add('t_shaftR', mirror(norm(TILES.shaftL, 16, 16)), 16, 16, PAL.chimney);
  // the cellar's flue: the chimney turned on its side
  const rot = rows => { const g = norm(rows, 16, 16); return g.map((r, y) => g.map(row => row[y]).join('')).map(r => r.split('').reverse().join('')); };
  add('t_flueT', rot(TILES.lipL), 16, 16, PAL.chimney);
  add('t_flueB', rot(mirror(norm(TILES.lipL, 16, 16))), 16, 16, PAL.chimney);
  add('t_flueShaft', rot(TILES.shaftL), 16, 16, PAL.chimney);
  add('t_bridge', TILES.bridge, 16, 16, PAL.bridge);
  add('t_water0', TILES.water0, 16, 16, PAL.water); add('t_water1', TILES.water1, 16, 16, PAL.water);
  add('t_winch', TILES.winch, 16, 16, PAL.winch);
  add('t_pennant', TILES.pennant, 16, 16, PAL.pennant);
  add('t_finial', TILES.finial, 16, 16, PAL.finial);
  return S;
}
