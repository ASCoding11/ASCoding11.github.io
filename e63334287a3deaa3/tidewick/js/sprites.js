// derive frames that are small changes of others
function shift(rows, dy) { const w = rows[0].length, blank = '.'.repeat(w); return dy > 0 ? Array(dy).fill(blank).concat(rows.slice(0, rows.length - dy)) : rows.slice(-dy).concat(Array(-dy).fill(blank)); }
