// ---------- tiles (16×16), many built from small rules so they tile cleanly ----------
function cobble() {
  const g = Array.from({ length: 16 }, () => Array(16).fill('1'));
  const stone = (x0, y0, w, h) => {
    for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
      const gx = (x0 + x + 16) % 16, gy = y0 + y;
      const corner = (x === 0 || x === w - 1) && (y === 0 || y === h - 1);
      if (corner) continue;
      g[gy][gx] = (y === 0 || (x === 0 && y < h - 1)) ? '3' : (y === h - 1 || x === w - 1) ? '1' : '2';
    }
  };
  stone(0, 0, 7, 7); stone(8, 0, 8, 7); stone(4, 8, 7, 7); stone(12, 8, 8, 7);
  g[2][3] = '3'; g[10][14] = '3';
  return g.map(r => r.join(''));
}
function blocks(rowsOf) {   // squared stone (fortress, stairs, cellar bricks)
  const g = Array.from({ length: 16 }, () => Array(16).fill('2'));
  for (let y = 0; y < 16; y++) for (let x = 0; x < 16; x++) {
    if (rowsOf === 'stair') {
      if (x === 0 || y === 0) g[y][x] = '3';
      if (x === 15 || y === 15) g[y][x] = '1';
      if ((x === 2 || x === 13) && y > 1 && y < 14) g[y][x] = '1';
      if ((y === 2 || y === 13) && x > 1 && x < 14) g[y][x] = '1';
      if ((x === 3 && y > 2 && y < 13) || (y === 3 && x > 2 && x < 13)) g[y][x] = '3';
    } else {
      const off = (Math.floor(y / 8) % 2) ? 8 : 0;
      if (y % 8 === 7) g[y][x] = '1';
      else if ((x + off) % 16 === 15) g[y][x] = '1';
      else if (y % 8 === 0 || (x + off) % 16 === 0) g[y][x] = '3';
    }
  }
  if (rowsOf !== 'stair') { g[3][4] = '1'; g[11][11] = '1'; g[4][12] = '3'; }
  return g.map(r => r.join(''));
}
