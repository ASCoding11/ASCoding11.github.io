// fixes the grid to exactly w × h ('.' fills, extra cut), so a stray character can't shift a sprite
function norm(rows, w, h) {
  const out = [];
  for (let y = 0; y < h; y++) { const r = (rows[y] || '').replace(/ /g, '1'); out.push((r + '.'.repeat(w)).slice(0, w)); }
  return out;
}

